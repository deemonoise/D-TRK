#!/usr/bin/env python3
"""Generate bounded SAMPLE anti-alias coefficient banks (stdlib only)."""
from pathlib import Path
import math

TAPS, PHASES, BANDS = 20, 32, 33
FIRST = 1 - TAPS // 2


def tap_count(band):
    return max(TAPS, 2 * math.ceil(4.5 * 2 ** (band / 8)))


def blackman(position):
    if abs(position) >= 1:
        return 0
    return .42 + .5 * math.cos(math.pi * position) + .08 * math.cos(2 * math.pi * position)


def sinc_value(distance):
    return math.sin(math.pi * distance) / (math.pi * distance) if distance else 1


def kernel_value(distance, cutoff=.45, width=4.5):
    return sinc_value(2 * cutoff * distance) * blackman(distance / width)


def high_kernel(key):
    rate = 2 ** (key / 64)
    transition = max(0, (rate - 128) / 128)
    width = 4.5 - .5 * transition
    radius = math.ceil(width * rate)
    values = [kernel_value(distance / rate, .45 - .05 * transition, width) for distance in range(radius)]
    total = values[0] + 2 * sum(values[1:])
    packed = [math.floor(value * 32768 / total + .5) for value in values]
    full_sum = packed[0] + 2 * sum(packed[1:])
    packed[0] += 32768 - full_sum
    return packed + [0]


def coefficients(band, phase):
    cutoff = .45 / (2 ** (band / 8))
    fraction = phase / PHASES
    taps = tap_count(band)
    out = []
    for tap in range(1 - taps // 2, 1 + taps // 2):
        offset = tap - fraction
        z = 2 * cutoff * offset
        sinc = math.sin(math.pi * z) / (math.pi * z) if z else 1
        out.append(sinc * blackman(offset / (taps / 2)))
    total = sum(out)
    return [value / total for value in out]


def quantized_coefficients(band, phase):
    source = coefficients(band, phase)
    result = [math.floor(value * 32768 + .5) for value in source]
    center = len(result) // 2 - 1 + (phase >= PHASES // 2)
    result[center] += 32768 - sum(result)
    return result


def high_arrays():
    lines, metadata = [], []
    for key in range(257, 513):
        packed = high_kernel(key)
        name = 'kSampleFirHigh%d' % key
        lines.append('static const int16_t %s[%d] MT_SAMPLE_COEFS = {' % (name, len(packed)))
        for first in range(0, len(packed), 16):
            lines.append('  ' + ', '.join(str(value) for value in packed[first:first + 16]) + ',')
        lines.append('};')
        metadata.append('  {%s, %d},' % (name, len(packed) - 1))
    lines.append('static const SampleFirKernelBank kSampleFirKernelBanks[256] MT_SAMPLE_COEFS = {')
    lines.extend(metadata)
    lines.append('};')
    return lines


def render_table():
    lines = ['// Generated by scripts/generate_sample_fir.py; do not edit by hand.',
             '// 32 interpolated phases; max(20,2ceil(4.5rate))taps through16x; packed half-kernels above16x, all1/64octave keys.',
             '#if defined(__IMXRT1062__)', '#define MT_SAMPLE_COEFS PROGMEM',
             '#else', '#define MT_SAMPLE_COEFS', '#endif']
    for band in range(BANDS):
        taps = tap_count(band)
        lines.append('static const int16_t kSampleFirBand%d[33][%d] MT_SAMPLE_COEFS = {' % (band, taps))
        for phase in range(PHASES + 1):
            values = [str(value) for value in quantized_coefficients(band, phase)]
            lines.append('    {' + ', '.join(values) + '},')
        lines.append('};')
    lines.append('static const SampleFirBank kSampleFirBanks[33] MT_SAMPLE_COEFS = {')
    for band in range(BANDS):
        lines.append('  {&kSampleFirBand%d[0][0], %d},' % (band, tap_count(band)))
    lines.append('};')
    lines.extend(high_arrays())
    lines.append('#undef MT_SAMPLE_COEFS')
    return '\n'.join(lines) + '\n'


def main():
    destination = Path(__file__).resolve().parents[1] / 'lib/core/src/synth_resample_table.inc'
    destination.write_text(render_table())


if __name__ == '__main__':
    main()
